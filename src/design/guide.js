export function designGuidance() {
  return {
    command: ["design", "guide"],
    optional: true,
    description:
      "Choose inputs by goal; inspect existing files, then create/find/prepare missing prerequisites before execution. This is advisory, not an enforced workflow.",
    documentation: installed("docs/DESIGN_INPUTS.md"),
    topics: Object.keys(recipes),
  };
}

export function designGuide(topic = "overview") {
  if (topic !== "overview" && !Object.hasOwn(recipes, topic)) {
    const error = new Error(
      "Unknown guide topic: " +
        topic +
        ". Use overview or " +
        Object.keys(recipes).join(", ") +
        ".",
    );
    error.exitCode = 2;
    throw error;
  }
  const recipe = recipes[topic];
  return {
    format: "chipsim-design-guide",
    version: 1,
    topic,
    ...designGuidance(),
    agentPreparation: [
      "Choose the smallest useful target from the user's intent and existing files. Recipes are optional: skip irrelevant stages, revisit them or combine them with an existing workflow.",
      "Inventory existing inputs, generated inputs, missing files and missing tools. Reuse valid project work; do not overwrite files or ask for generated outputs as mandatory uploads.",
      "For missing inputs, search the project/installed examples first; author design RTL, harnesses and configuration within the requested scope, or locate compatible licensed upstream IP/tool/PDK sources and record revisions. Do useful preparation before running; explain actual blockers.",
      "Resolve material unknowns such as ISA, interfaces, memory map and clock/reset requirements from available evidence or ask for them. Record reasonable illustrative choices as assumptions; never present them as vendor facts.",
      "Declare every consumed source, helper, header, test vector and configuration. For generated files, add a producer task and an artifact binding; do not require the file to pre-exist or insert placeholder evidence.",
      "Probe required installed tools with doctor after inputs exist. Tool installation follows the agent's existing permissions; this guidance does not install tools, providers or modify agent settings.",
      "Run an appropriate check/simulation, inspect failures and artifacts, and report scope and remaining gaps. Logs, waveforms, reports, proofs and layout come from real execution; never fabricate passing results.",
    ],
    formats,
    workflows: Object.entries(recipes).map(([id, r]) => ({
      id,
      purpose: r.purpose,
      command: ["design", "guide", id],
    })),
    ...(recipe
      ? {
          recipe: {
            ...recipe,
            ...(recipe.example ? { example: installed(recipe.example) } : {}),
          },
        }
      : {}),
    starter: {
      directory: installed("examples/design/minimal"),
      files: [
        "counter.v",
        "counter_tb.v",
        "sim.project.json",
        "chipsim.design.json",
        "chipsim.lock.json",
      ],
      action:
        "Copy to a new directory or adapt the source/manifest examples to the requested design. The first three files suffice for hdl run; all five support managed design run. This command only describes them and writes nothing.",
      target: "simulation",
    },
    documentation: {
      inputs: installed("docs/DESIGN_INPUTS.md"),
      design: installed("docs/DESIGN.md"),
      hdl: installed("docs/HDL.md"),
      programming: installed("docs/PROGRAMMING.md"),
    },
    argumentConvention:
      "Command arrays omit the chipsim executable. Uppercase placeholders are replaced with actual paths/IDs; never pass them literally. Commands are alternatives or suggestions, not an automatic sequence.",
  };
}
