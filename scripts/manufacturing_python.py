"""Validate a managed virtual environment's versions and installed wheel records."""
import base64
import hashlib
import importlib.metadata
from pathlib import Path
import re
import sys


def canonical(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def verify(lock, paths=None):
    expected = dict((canonical(name), version) for name, version in
                    re.findall(r'^([\w.-]+)==([^\s;\\]+)', Path(lock).read_text(), re.M))
    installed = {}
    for distribution in importlib.metadata.distributions(**({"path": paths} if paths is not None else {})):
        name = canonical(distribution.metadata['Name'])
        installed[name] = distribution.version
        if name not in expected and name not in ['pip', 'setuptools']:
            raise ValueError('Unexpected cached Python distribution: ' + name)
        if name in expected and installed[name] != expected[name]:
            raise ValueError('Cached Python version differs from lock: ' + name)
        if distribution.files is None:
            raise ValueError('Installed distribution lacks a file inventory: ' + name)
        for file in distribution.files:
            if file.hash is None:
                continue  # RECORD itself and generated bytecode have no wheel hash.
            path = Path(distribution.locate_file(file))
            h = hashlib.new(file.hash.mode)
            with path.open('rb') as stream:
                while chunk := stream.read(1024 * 1024):
                    h.update(chunk)
            actual = base64.urlsafe_b64encode(h.digest()).decode().rstrip('=')
            if actual != file.hash.value:
                raise ValueError('Installed Python file differs from its wheel record: ' + str(path))
    missing = set(expected) - set(installed)
    if missing:
        raise ValueError('Incomplete cached Python environment: ' + ', '.join(sorted(missing)))


if __name__ == '__main__':
    verify(sys.argv[1])
    print('Verified installed Python versions and wheel file hashes')
